// 模糊概念的骰子（2026-10-29 主人定规）
//
// 原话：「模棱两可的概念，比如可能或者可以，甚至区间性比如"1~2个气泡"，总之，以后如果出现了没有
// 明确指向性的概念，为了避免绝对化或者矫枉过正，干脆统一引入概率投掷骰子」。
//
// 为什么要有这个文件：区间规则写进代码时最容易被钉成硬阈值（>60 字必拆），写进提示词时最容易变成
// 绝对化（一律两条 / 一律一条）。两种做法都是把"看情况"写成了"一定"，而"看情况"正是人的样子。
// 所以凡是**都说得过去**的区间，就交给一次掷骰，而不是某一面永远赢。
//
// 边界（不许拿骰子糊弄的地方）：事实、安全、礼貌底线、配额（每天几条）、要不要动手——这些不是
// 区间，是硬约束，骰子不参与。骰子只裁决"怎么表现"，不裁决"做不做"。
//
// 为什么用文本指纹而不是 Math.random：桥的幂等账本按真正发出去的碎片记账，同一条原文重发时
// 必须得到同一个结果，否则重发对不上账、会被当成新消息再发一遍。指纹骰子对同一条原文永远是同一面，
// 对不同原文之间仍然各自独立——概率该有的样子都在。

/** 0~1 的稳定随机数：同样的 seed 永远同一个结果，不同 seed 之间近似均匀。 */
export function stableRoll(seed) {
  const s = String(seed ?? '');
  let h = 2166136261 >>> 0;                     // FNV-1a
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  // 再搅一次，避免相邻/同尾文本在小样本上贴得太近
  h ^= h >>> 15;
  h = Math.imul(h, 2246822507) >>> 0;
  h ^= h >>> 13;
  return (h >>> 0) / 4294967296;   // 位运算返回有符号 32 位，不 >>>0 会把整段负值压到同一面
}

/** 掷一次：p 概率为真。 */
export function rollOnce(p) {
  const x = Math.min(1, Math.max(0, Number(p) || 0));
  return x > 0 && Math.random() < x;
}
